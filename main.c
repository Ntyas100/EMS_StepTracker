/* USER CODE BEGIN 4 */
int8_t CheckButtonPressed()
{
  GPIO_PinState current_state = HAL_GPIO_ReadPin(GPIOC, GPIO_PIN_13);

  if(current_state != button_last_reading){
	  last_debounce_time = HAL_GetTick();
	  button_last_reading = current_state;
  }

  if((HAL_GetTick()- last_debounce_time)> 50){ // Threshold for debounce
	  if(button_state != current_state){
		  button_state = current_state;		   // Update button state if threshold passed

		  if(button_state == GPIO_PIN_RESET){ // If True then button pressed
			  return 1;
		  }
	  }
  }

  return 0;

}
